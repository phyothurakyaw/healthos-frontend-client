const translations = {
  en,
  my,
  zh,
  es,
};

/**
 * Translate a UI label.
 *
 * @param {string} lang - en, my, zh, es
 * @param {string} key - translation key
 * @returns {string}
 *
 * Examples:
 * t("en", "dashboard") => "Dashboard"
 * t("my", "dashboard") => "ဒက်ရှ်ဘုတ်"
 * t("zh", "dashboard") => "仪表盘"
 * t("es", "dashboard") => "Panel"
 */
export function t(lang, key) {
  const dictionary = translations[lang] || en;

  return dictionary[key] ?? en[key] ?? key;
}

export default translations;
